import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../site/workshop/', import.meta.url);
export const starter = {
  title: 'The small victories department',
  code: (await readFile(new URL('app.js', source), 'utf8')).trimEnd(),
  css: await readFile(new URL('style.css', source), 'utf8'),
};
const provenance = JSON.parse(await readFile(new URL('../content/provenance.json', import.meta.url), 'utf8'));
const demos = JSON.parse(await readFile(new URL('../site/vendor/demos.provenance.json', import.meta.url), 'utf8'));
if (demos.coreSha256 !== provenance.bundleSha256 || demos.dataVersion !== provenance.packageVersion) throw new Error('Workshop requires matching core and data vendor provenance.');
export const runtime = {
  package: 'marionette',
  version: provenance.packageVersion,
  revision: provenance.libraryRevision,
  data: { package: '@mnjs/data', version: demos.dataVersion },
};
const output = new URL('../site/assets/workshop-starter.js', import.meta.url);
const generated = '// Generated by scripts/build-workshop-starter.mjs from site/workshop/ and vendor provenance.\n' +
  `export const starter = ${JSON.stringify(starter, null, 2)};\n` +
  `export const runtime = ${JSON.stringify(runtime, null, 2)};\n`;
const previous = await readFile(output, 'utf8').catch(error => {
  if (error.code === 'ENOENT') return null;
  throw error;
});
if (previous !== generated) await writeFile(output, generated);
